import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import { stripEmbeddedAyahMarkers } from '../src/data/fonts.js';
import { warshToHafsNumbers } from '../src/data/warshHafsNumbering.js';
import { archiveWordKey, projectArchiveRange } from '../src/utils/warshArchiveRules.js';

const sourceBytes = await fs.readFile(process.argv[2]);
const source = JSON.parse(sourceBytes);
const corpusBytes = await fs.readFile('public/data/warsh-page-source.json');
const corpus = JSON.parse(corpusBytes);
const verses = new Map(source.verses.map(verse => [verse.verse_key, verse]));
const rules = {
  MaddLazim: 'madd', MaddMuttasil: 'madd-connected', MaddMunfasil: 'madd-obligatory-separated',
  MaddBadal: 'madd-badal', MaddArid: 'madd-arid', MaddLin: 'madd-lin', MaddTabeei: 'madd-normal', MaddSilah: 'madd-normal',
  QalqalahSughra: 'qalqala', QalqalahKubra: 'qalqala', QalqalahAkbar: 'qalqala',
  IkhfaaHaqiqi: 'ikhfa', IkhfaaShafawi: 'ikhfa-shafawi', IdghamBiGhunnah: 'idgham-ghunnah', GhunnahMushadda: 'ghunna', Iqlab: 'iqlab',
  IdghamBilaGhunnah: 'idgham-without-ghunnah', IdghamShamsi: 'lam-shamsiyya', IdghamMithlayn: 'idgham-mutamathilayn',
  IdghamMutajanisayn: 'idgham-mutajanisayn', IdghamMutaqaribayn: 'idgham-mutaqaribayn', Silent: 'silent',
  TafkhimHuruf: 'tafkhim', TafkhimRa: 'tafkhim', TafkhimLafuljalala: 'tafkhim',
};
const rows = [];
const skipped = [];
let paintedWords = 0;
for (const verse of corpus) {
  const text = stripEmbeddedAyahMarkers(verse.aya_text, { ayahNumber: verse.aya_no }).normalize('NFC');
  const targets = text.split(/\s+/u).filter(Boolean);
  const numbers = warshToHafsNumbers(verse.sura_no, verse.aya_no);
  const sources = [];
  for (const number of numbers || []) {
    const candidate = verses.get(`${verse.sura_no}:${number}`);
    if (!candidate) continue;
    const points = [...candidate.text_ar];
    const offsets = [0];
    points.forEach(point => offsets.push(offsets.at(-1) + point.length));
    for (const match of candidate.text_ar.matchAll(/\S+/gu)) {
      const ranges = [];
      for (const segment of candidate.tajweed_segments) {
        const start = offsets[segment.start]; const end = offsets[segment.end];
        if (start >= match.index + match[0].length || end <= match.index) continue;
        const ruleId = segment.rules.map(rule => rules[rule]).find(Boolean);
        if (ruleId) ranges.push({ start: Math.max(0, start - match.index), end: Math.min(match[0].length, end - match.index), ruleId });
      }
      if (archiveWordKey(match[0])) sources.push({ text: match[0], ranges });
    }
  }
  // Standalone signs (the rub al-hizb marker) are tokens of the printed verse but
  // have no letters, hence no key: the archive has no word for them. They stay out
  // of the match and keep an empty range list, so the verses that open a rub are
  // aligned like the others.
  const usableTargets = targets.map((target, i) => ({ target, i })).filter(({ target }) => archiveWordKey(target));
  const targetKeys = usableTargets.map(({ target }) => archiveWordKey(target));
  const matches = sources.map((_, i) => i).filter(i => targetKeys.every((key, j) => key === archiveWordKey(sources[i + j]?.text || '')));
  if (matches.length !== 1) { skipped.push(`${verse.sura_no}:${verse.aya_no}`); continue; }
  const sourceIndexOf = new Map(usableTargets.map(({ i }, j) => [i, matches[0] + j]));
  const ranges = targets.map((target, i) => {
    if (!sourceIndexOf.has(i)) return [];
    const from = sources[sourceIndexOf.get(i)];
    const projected = from.ranges.map(range => projectArchiveRange(from.text, target, range)).filter(Boolean);
    // Font/diacritic equivalents may expand two ranges onto one cluster.
    // The first source rule owns that cluster; ranges stay disjoint.
    const disjoint = [];
    for (const range of projected.sort((a, b) => a.start - b.start)) {
      const previous = disjoint.at(-1);
      const start = Math.max(range.start, previous?.end || 0);
      if (range.end > start) disjoint.push({ ...range, start });
    }
    return disjoint;
  });
  paintedWords += ranges.filter(list => list.length).length;
  rows.push([text, ranges]);
}
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const meta = {
  version: 1, source: 'user-warsh-tajweed-archive', sourceJsonSha256: sha(sourceBytes), corpusSha256: sha(corpusBytes),
  numbering: 'warsh-madinah', sourceNumbering: 'hafs-kufi', validatedByScholar: false,
  alignedAyahs: rows.length, skippedAyahs: skipped.length, paintedWords, ruleIds: [...new Set(Object.values(rules))],
};
const output = JSON.stringify({ meta, rows });
await fs.writeFile('public/data/warsh-tajweed-archive.json', output);
await fs.writeFile('src/data/warshArchiveManifest.js', `// Generated by scripts/build-warsh-tajweed-archive.mjs.\nexport const WARSH_ARCHIVE_SHA256 = '${sha(output)}';\nexport const WARSH_ARCHIVE_RULE_IDS = Object.freeze(${JSON.stringify(meta.ruleIds)});\n`);
await fs.writeFile('.codex-artifacts/warsh-archive-integration.json', JSON.stringify({ ...meta, skipped }, null, 2));
console.log(JSON.stringify(meta, null, 2));
