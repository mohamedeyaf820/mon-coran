// scratch: build percent-encoded Arabic Wikipedia titles from codepoints
const titles = {
  basfar: [0x0639, 0x0628, 0x062f, 0x0627, 0x0644, 0x0644, 0x0647, 0x0020, 0x0628, 0x0646, 0x0020, 0x0639, 0x0644, 0x064a, 0x0020, 0x0628, 0x0635, 0x0641, 0x0631],
  matrood: [0x0639, 0x0628, 0x062f, 0x0627, 0x0644, 0x0644, 0x0647, 0x0020, 0x0627, 0x0644, 0x0645, 0x0637, 0x0631, 0x0648, 0x062f],
};
for (const [k, cps] of Object.entries(titles)) {
  const s = String.fromCodePoint(...cps);
  console.log(`${k}\thttps://ar.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(s)}`);
}
